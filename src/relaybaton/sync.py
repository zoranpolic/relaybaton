"""Generate per-agent instruction files from one source file."""

from __future__ import annotations

import difflib
import hashlib
import re
from dataclasses import dataclass
from enum import Enum

from relaybaton.config import Config, ConfigError

MARKER = "relaybaton:generated"
_MARKER_RE = re.compile(r"<!--\s*relaybaton:generated\b")


class State(str, Enum):
    OK = "ok"
    MISSING = "missing"
    DRIFTED = "drifted"  # generated file whose content no longer matches the source
    UNMANAGED = "unmanaged"  # a hand-written file sits where a generated one belongs


@dataclass(frozen=True)
class TargetStatus:
    agent: str
    path: str
    state: State
    expected: str
    actual: str | None

    def diff(self) -> str:
        if self.actual is None:
            return ""
        return "".join(
            difflib.unified_diff(
                self.actual.splitlines(keepends=True),
                self.expected.splitlines(keepends=True),
                fromfile=f"{self.path} (on disk)",
                tofile=f"{self.path} (expected)",
            )
        )


def overlay_name(agent: str) -> str:
    return f"AGENTS.{agent}.md"


CURSOR_FRONT_MATTER = (
    "---\n"
    "description: Project instructions for AI coding agents, generated by relaybaton\n"
    "alwaysApply: true\n"
    "---\n"
)


def render(config: Config, agent: str) -> str:
    """Return the exact content the target file for ``agent`` should have.

    Cursor project rules (``*.mdc``) need YAML front matter on the very first
    line, so for those targets it goes above relaybaton's generated header.
    """
    source_path = config.path(config.source)
    if not source_path.is_file():
        raise ConfigError(f"source file not found: {config.source}")
    body = source_path.read_text(encoding="utf-8").rstrip("\n") + "\n"

    overlay = config.path(overlay_name(agent))
    if overlay.is_file():
        body += "\n" + overlay.read_text(encoding="utf-8").rstrip("\n") + "\n"

    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()[:12]
    edit_hint = config.source
    if overlay.is_file():
        edit_hint += f" or {overlay_name(agent)}"
    header = (
        f"<!-- {MARKER} source={config.source} agent={agent} sha256={digest} -->\n"
        f"<!-- Do not edit this file. Edit {edit_hint} and run `baton sync`. -->\n\n"
    )
    target = config.targets.get(agent, "")
    prefix = CURSOR_FRONT_MATTER if target.endswith(".mdc") else ""
    return prefix + header + body


def _is_generated(text: str) -> bool:
    """True when the relaybaton marker sits in the file's opening lines."""
    return any(_MARKER_RE.search(line) for line in text.split("\n", 8)[:8])


def plan(config: Config) -> list[TargetStatus]:
    """Compare every target on disk with what it should contain."""
    statuses = []
    for agent, target in sorted(config.targets.items()):
        expected = render(config, agent)
        path = config.path(target)
        if not path.exists():
            statuses.append(TargetStatus(agent, target, State.MISSING, expected, None))
            continue
        actual = path.read_text(encoding="utf-8")
        if actual == expected:
            state = State.OK
        elif _is_generated(actual):
            state = State.DRIFTED
        else:
            state = State.UNMANAGED
        statuses.append(TargetStatus(agent, target, state, expected, actual))
    return statuses


def write(config: Config, force: bool = False) -> list[TargetStatus]:
    """Bring every target up to date and return the statuses found before writing.

    Hand-written files (``UNMANAGED``) are left alone unless ``force`` is set, so
    a first run never destroys someone's existing CLAUDE.md.
    """
    statuses = plan(config)
    for status in statuses:
        if status.state is State.OK:
            continue
        if status.state is State.UNMANAGED and not force:
            continue
        path = config.path(status.path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(status.expected, encoding="utf-8")
    return statuses
